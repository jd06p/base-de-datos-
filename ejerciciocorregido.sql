    ADD CONSTRAINT equipo_cliente_fk FOREIGN KEY (cliente_run_cliente)
        REFERENCES cliente (run_cliente);

ALTER TABLE solicitar
    ADD CONSTRAINT solicitar_cliente_fk FOREIGN KEY (cliente_run_cliente)
        REFERENCES cliente (run_cliente);

ALTER TABLE revisar
    ADD CONSTRAINT revisar_trabajador_fk FOREIGN KEY (trabajador_run_trabajador)
        REFERENCES trabajador (run_trabajador);

ALTER TABLE revisar
    ADD CONSTRAINT revisar_equipo_fk FOREIGN KEY (equipo_id_equipo)
        REFERENCES equipo (id_equipo);

ALTER TABLE trabajos_realizados
    ADD CONSTRAINT trabajos_trabajador_fk FOREIGN KEY (trabajador_run_trabajador)
        REFERENCES trabajador (run_trabajador);

ALTER TABLE trabajos_realizados
    ADD CONSTRAINT trabajos_servicios_fk FOREIGN KEY (servicios_id_servicio)
        REFERENCES servicios (id_servicio);

  
