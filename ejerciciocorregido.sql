--==============================================================================
--01 - CREACION DE TABLAS
--==============================================================================

CREATE TABLE ciudad (
    id_ciudad     NUMBER NOT NULL,
    nombre_ciudad VARCHAR2(50) NOT NULL,
    pais_id_pais  NUMBER NOT NULL
);

ALTER TABLE ciudad ADD CONSTRAINT ciudad_pk PRIMARY KEY ( id_ciudad );

CREATE TABLE comuna (
    id_comuna        NUMBER NOT NULL,
    nombre_comuna    VARCHAR2(50) NOT NULL,
    ciudad_id_ciudad NUMBER NOT NULL
);

ALTER TABLE comuna ADD CONSTRAINT comuna_pk PRIMARY KEY ( id_comuna );

CREATE TABLE pais (
    id_pais     NUMBER NOT NULL,
    nombre_pais VARCHAR2(50) NOT NULL
);

ALTER TABLE pais ADD CONSTRAINT pais_pk PRIMARY KEY ( id_pais );

CREATE TABLE servicios (
    id_servicio      NUMBER NOT NULL,
    nombre_servicio  VARCHAR2(50) NOT NULL,
    detalle_servicio VARCHAR2(200) NOT NULL,
    costo_servicio   NUMBER NOT NULL
);

ALTER TABLE servicios ADD CONSTRAINT servicios_pk PRIMARY KEY ( id_servicio );

CREATE TABLE solicitar (
    cliente_run_cliente   VARCHAR2(13) NOT NULL,
    servicios_id_servicio NUMBER NOT NULL
);

ALTER TABLE solicitar ADD CONSTRAINT solicitar_pk PRIMARY KEY ( cliente_run_cliente,
                                                                servicios_id_servicio );

-- Tablas faltantes indicadas en el modelo relacional.
CREATE TABLE cliente (
    run_cliente       VARCHAR2(13) NOT NULL,
    pnombre_cliente   VARCHAR2(20) NOT NULL,
    snombre_cliente   VARCHAR2(20) NOT NULL,
    appaterno_cliente VARCHAR2(20) NOT NULL,
    apmaterno_cliente VARCHAR2(20),
    direccion_cliente VARCHAR2(100) NOT NULL,
    edad_cliente      NUMBER(3) NOT NULL,
    fono_cliente      NUMBER(10) NOT NULL,
    comuna_id_comuna  NUMBER NOT NULL
