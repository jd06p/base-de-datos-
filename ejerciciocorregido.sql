ALTER TABLE cliente ADD CONSTRAINT cliente_pk PRIMARY KEY (run_cliente);

CREATE TABLE trabajador (
    run_trabajador       VARCHAR2(13) NOT NULL,
    pnombre_trabajador   VARCHAR2(20) NOT NULL,
    snombre_trabajador   VARCHAR2(20) NOT NULL,
    appaterno_trabajador VARCHAR2(20) NOT NULL,
    apmaterno_trabajador VARCHAR2(20),
    direccion_trabajador VARCHAR2(100) NOT NULL,
    edad_trabajador      NUMBER(3) NOT NULL,
    fono_trabajador      NUMBER(10) NOT NULL,
    cargo_trabajador     VARCHAR2(50) NOT NULL,
    comuna_id_comuna     NUMBER NOT NULL
);
ALTER TABLE trabajador ADD CONSTRAINT trabajador_pk PRIMARY KEY (run_trabajador);

-- Tabla adicional para normalizar el atributo tipo_equipo.
CREATE TABLE tipo_equipo (
    id_tipo_equipo     NUMBER NOT NULL,
    nombre_tipo_equipo VARCHAR2(20) NOT NULL
);
ALTER TABLE tipo_equipo ADD CONSTRAINT tipo_equipo_pk PRIMARY KEY (id_tipo_equipo);
ALTER TABLE tipo_equipo ADD CONSTRAINT tipo_equipo_nombre_un UNIQUE (nombre_tipo_equipo);

CREATE TABLE equipo (
    id_equipo                  NUMBER NOT NULL,
    marca_equipo               VARCHAR2(20) NOT NULL,
    modelo_equipo              VARCHAR2(20) NOT NULL,
    tipo_equipo_id_tipo_equipo NUMBER NOT NULL,
    detalle_equipo             VARCHAR2(200) NOT NULL,
    cliente_run_cliente        VARCHAR2(13) NOT NULL
);
ALTER TABLE equipo ADD CONSTRAINT equipo_pk PRIMARY KEY (id_equipo);

CREATE TABLE revisar (
    trabajador_run_trabajador VARCHAR2(13) NOT NULL,
    equipo_id_equipo          NUMBER NOT NULL
);
ALTER TABLE revisar ADD CONSTRAINT revisar_pk PRIMARY KEY (trabajador_run_trabajador, equipo_id_equipo);

CREATE TABLE trabajos_realizados (
    trabajador_run_trabajador VARCHAR2(13) NOT NULL,
    servicios_id_servicio     NUMBER NOT NULL
);
ALTER TABLE trabajos_realizados ADD CONSTRAINT trabajos_realizados_pk PRIMARY KEY (trabajador_run_trabajador, servicios_id_servicio);

--==============================================================================
-- 02 MODIFICACION DE TABLAS PARA AGREGAR FOREIGN KEY
