--==============================================================================
--  CONSULTA 1: EQUIPOS NOTEBOOK
--==============================================================================
SELECT id_equipo AS "CODIGO EQUIPO",
       marca_equipo || ' ' || modelo_equipo AS "EQUIPO",
       nombre_tipo_equipo AS "TIPO EQUIPO"
FROM equipo
JOIN tipo_equipo ON tipo_equipo_id_tipo_equipo = id_tipo_equipo
WHERE nombre_tipo_equipo = 'NOTEBOOK'
ORDER BY nombre_tipo_equipo ASC;

--==============================================================================
--  CONSULTA 2: CLIENTES ENTRE 15 Y 30 A�OS
--==============================================================================
SELECT run_cliente AS "RUN CLIENTE",
       pnombre_cliente || ' ' || snombre_cliente || ' ' || appaterno_cliente ||
       CASE WHEN apmaterno_cliente IS NOT NULL THEN ' ' || apmaterno_cliente ELSE '' END AS "NOMBRE CLIENTE",
       direccion_cliente AS "DIRECCION",
       edad_cliente AS "EDAD"
FROM cliente
WHERE edad_cliente BETWEEN 15 AND 30
ORDER BY appaterno_cliente ASC;

